/// Supported languages.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Zh,
    En,
}

impl Lang {
    pub fn toggle(&self) -> Self {
        match self {
            Lang::Zh => Lang::En,
            Lang::En => Lang::Zh,
        }
    }
}

macro_rules! t {
    ($lang:expr, $key:ident) => {
        $crate::i18n::text($lang, $crate::i18n::Key::$key)
    };
}
pub(crate) use t;

